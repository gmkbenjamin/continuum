// After hitting the limit the user runs a local slash command (/usage). Claude
// Code records a meta "local-command-caveat" user line plus the command; no
// model turn happens. Continuum treats it as the session having continued.
func TestLocalSlashCommandDoesNotCancelResume(t *testing.T) {
	h := setup(t)
	path := filepath.Join(h.claude, "projects", "-work-app", "s1.jsonl")
	limit := `{"type":"assistant","sessionId":"s1","cwd":"/work/app","timestamp":"` + h.now.Format(time.RFC3339) + `","isApiErrorMessage":true,"error":"rate_limit","message":{"content":[{"type":"text","text":"You've hit your session limit · resets 9:30am (UTC)"}]}}` + "\n"
	os.WriteFile(path, []byte(limit), 0o600)
	ev := limitEvent(h, "s1", 30*time.Minute)
	ev.TranscriptPath = path
	ev.TranscriptSize = int64(len(limit))
	h.d.Handle(ev)
	f, _ := os.OpenFile(path, os.O_APPEND|os.O_WRONLY, 0)
	at := h.now.Add(5 * time.Second).Format(time.RFC3339)
	f.WriteString(`{"type":"user","isMeta":true,"sessionId":"s1","timestamp":"` + at + `","message":{"role":"user","content":"<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>"}}` + "\n")
	f.WriteString(`{"type":"user","sessionId":"s1","timestamp":"` + at + `","message":{"role":"user","content":"<command-name>/usage</command-name>\n<command-message>usage</command-message>\n<command-args></command-args>"}}` + "\n")
	f.Close()
	h.advance(32 * time.Minute)
	j := h.d.Jobs["claude:s1"]
	t.Logf("state=%s result=%q delivered=%d", j.State, j.Result, len(h.delivered))
	if len(h.delivered) == 0 {
		t.Errorf("a local /usage command after the limit stopped Continuum from resuming")
	}
}

// Two Codex sessions in the same folder, each in its own wrapper (hooks
// recorded where each runs). The shared usage limit hits both. Rollout events
// carry no location, so findTwin matches by folder and can bind session X's
// job to session Y's wrapper.
func TestCodexSameFolderJobsKeepTheirWrappers(t *testing.T) {
	wrong := 0
	for i := 0; i < 40; i++ {
		h := setup(t)
		for _, s := range []struct{ id, w string }{{"X", "wA"}, {"Y", "wB"}} {
			h.d.Handle(core.Event{Harness: "codex", Kind: core.KindSessionStart, SessionID: s.id, Cwd: "/w", At: h.now.Add(-time.Hour), Source: "hook:SessionStart", Location: &core.Location{Kind: "wrapper", Target: s.w}})
		}
		// Wrapper screens report first (location, no session id)...
		h.d.Handle(core.Event{Harness: "codex", Kind: core.KindUsageLimit, Cwd: "/w", At: h.now, ResetAt: h.now.Add(time.Hour), Source: "wrapper", Location: &core.Location{Kind: "wrapper", Target: "wA"}})
		h.d.Handle(core.Event{Harness: "codex", Kind: core.KindUsageLimit, Cwd: "/w", At: h.now, ResetAt: h.now.Add(time.Hour), Source: "wrapper", Location: &core.Location{Kind: "wrapper", Target: "wB"}})
		// ...then the rollouts (session id, no location).
		h.d.Handle(core.Event{Harness: "codex", Kind: core.KindUsageLimit, SessionID: "X", Cwd: "/w", At: h.now.Add(2 * time.Second), ResetAt: h.now.Add(time.Hour), Source: "rollout"})
		h.d.Handle(core.Event{Harness: "codex", Kind: core.KindUsageLimit, SessionID: "Y", Cwd: "/w", At: h.now.Add(2 * time.Second), ResetAt: h.now.Add(time.Hour), Source: "rollout"})
		if j := h.d.Jobs["codex:X"]; j != nil && j.Location != nil && j.Location.Target != "wA" {
			wrong++
		}
	}
	if wrong > 0 {
		t.Errorf("in %d/40 runs session X's resume was bound to session Y's wrapper", wrong)
	}
}

// Realistic timing: the rollout line is written at the error (T), the wrapper
// reports after its screen settles (T+2s). Check where deliveries land.
func TestCodexSameFolderBothResumed(t *testing.T) {
	missed := 0
	for i := 0; i < 40; i++ {
		h := setup(t)
		for _, s := range []struct{ id, w string }{{"X", "wA"}, {"Y", "wB"}} {
			h.d.Handle(core.Event{Harness: "codex", Kind: core.KindSessionStart, SessionID: s.id, Cwd: "/w", At: h.now.Add(-time.Hour), Source: "hook:SessionStart", Location: &core.Location{Kind: "wrapper", Target: s.w}})
		}
		T := h.now
		h.d.Handle(core.Event{Harness: "codex", Kind: core.KindUsageLimit, SessionID: "X", Cwd: "/w", At: T, ResetAt: T.Add(time.Hour), Source: "rollout"})
		h.d.Handle(core.Event{Harness: "codex", Kind: core.KindUsageLimit, SessionID: "Y", Cwd: "/w", At: T, ResetAt: T.Add(time.Hour), Source: "rollout"})
		h.d.Handle(core.Event{Harness: "codex", Kind: core.KindUsageLimit, Cwd: "/w", At: T.Add(2 * time.Second), ResetAt: T.Add(time.Hour), Source: "wrapper", Location: &core.Location{Kind: "wrapper", Target: "wA"}})
		h.d.Handle(core.Event{Harness: "codex", Kind: core.KindUsageLimit, Cwd: "/w", At: T.Add(2 * time.Second), ResetAt: T.Add(time.Hour), Source: "wrapper", Location: &core.Location{Kind: "wrapper", Target: "wB"}})
		h.advance(62 * time.Minute)
		got := map[string]bool{}
		for _, j := range h.delivered {
			got[j.Location.Target] = true
		}
		if !got["wA"] || !got["wB"] {
			missed++
			if missed == 1 {
				for k, j := range h.d.Jobs {
					t.Logf("job %s state=%s loc=%s result=%q", k, j.State, j.Location.String(), j.Result)
				}
			}
		}
	}
	if missed > 0 {
		t.Errorf("in %d/40 runs one of the two stalled sessions was never resumed", missed)
	}
}

