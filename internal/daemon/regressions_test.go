// `continuum resume-now all` means every pending resume: never a billing stop
// (needs you), a cancelled job, or a session that continued by itself.
func TestResumeNowAllLeavesFinishedJobsAlone(t *testing.T) {
	h := setup(t)
	// s1: billing error -> needs_user
	ev := limitEvent(h, "s1", 0)
	ev.Kind = core.KindNeverResume
	ev.Message = "Your credit balance is too low"
	h.d.Handle(ev)
	// s2: cancelled by the user
	e2 := limitEvent(h, "s2", time.Hour)
	e2.Location = &core.Location{Kind: "tmux", Target: "%2"}
	h.d.Handle(e2)
	h.d.Handle(core.Event{Kind: "control", Message: "cancel s2"})
	// s3: the session continued on its own -> skipped
	e3 := limitEvent(h, "s3", time.Hour)
	e3.Location = &core.Location{Kind: "tmux", Target: "%3"}
	h.d.Handle(e3)
	h.d.Handle(core.Event{Harness: "claude", Kind: core.KindActivity, SessionID: "s3", At: h.now.Add(time.Minute), Source: "hook:Stop"})
	for _, k := range []string{"claude:s1", "claude:s2", "claude:s3"} {
		t.Logf("%s before: %s", k, h.d.Jobs[k].State)
	}
	h.now = h.now.Add(2 * time.Minute)
	h.d.Handle(core.Event{Kind: "control", Message: "resume-now all"})
	for _, k := range []string{"claude:s1", "claude:s2", "claude:s3"} {
		t.Logf("%s after control: %s due=%s", k, h.d.Jobs[k].State, h.d.Jobs[k].DueAt)
	}
	h.advance(time.Second)
	for _, k := range []string{"claude:s1", "claude:s2", "claude:s3"} {
		t.Logf("%s after tick: %s %s", k, h.d.Jobs[k].State, h.d.Jobs[k].Result)
	}
	for _, j := range h.delivered {
		t.Errorf("resume-now all delivered to %s", j.Key)
	}
}

