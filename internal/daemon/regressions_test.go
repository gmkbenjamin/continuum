// Limit text read off the screen that is part of the agent's normal reply is
// not a stall, whichever arrives first.
func TestScreenLimitInsideAReplyIsNotAStall(t *testing.T) {
	reply := "I added handling so the CLI prints \"usage limit reached\" when the quota API returns 429."
	loc := &core.Location{Kind: "wrapper", Target: "w1"}
	screen := core.Event{Harness: "claude", Kind: core.KindUsageLimit, Source: "wrapper", Location: loc,
		Message: "the CLI prints \"usage limit reached\" when", Hit: "usage limit reached"}
	replyEv := core.Event{Harness: "claude", Kind: core.KindReply, SessionID: "s1", Source: "hook:Stop", Location: loc, Message: reply}

	h := setup(t)
	replyEv.At, screen.At = h.now, h.now.Add(2*time.Second)
	h.d.Handle(replyEv)
	h.d.Handle(screen)
	for k, j := range h.d.Jobs {
		if j.State == core.StatePending {
			t.Fatalf("reply first: scheduled %s", k)
		}
	}

	h = setup(t)
	screen.At, replyEv.At = h.now, h.now.Add(time.Second)
	h.d.Handle(screen)
	h.d.Handle(replyEv)
	for k, j := range h.d.Jobs {
		if j.State == core.StatePending {
			t.Fatalf("screen first: %s still pending", k)
		}
	}

	// A real StopFailure after such a reply is still a stall.
	h = setup(t)
	replyEv.At = h.now
	h.d.Handle(replyEv)
	ev := limitEvent(h, "s1", 30*time.Minute)
	ev.At = h.now.Add(time.Minute)
	h.d.Handle(ev)
	if j := h.d.Jobs["claude:s1"]; j == nil || j.State != core.StatePending {
		t.Fatalf("a real limit after a reply: %+v", j)
	}
}

func TestSelectors(t *testing.T) {
	j := &core.Job{Key: "claude:4f2c1d9e-0000-4000-8000-000000000001", Harness: "claude", SessionID: "4f2c1d9e-0000-4000-8000-000000000001"}
	for sel, want := range map[string]bool{
		"all": true, j.Key: true, j.SessionID: true, "4f2c": true, "4f2c1d9e": true,
		"": false, "4f2": false, "1": false, "0001": false, "claude:": false,
	} {
		if got := SelectorMatches(j, sel); got != want {
			t.Errorf("%q: %v want %v", sel, got, want)
		}
	}
	// An empty selector does nothing (it never means "all").
	h := setup(t)
	h.d.Handle(limitEvent(h, "s1", 30*time.Minute))
	h.d.Handle(core.Event{Kind: "control", Message: "cancel "})
	if j := h.d.Jobs["claude:s1"]; j.State != core.StatePending {
		t.Fatalf("an empty selector cancelled %s", j.Key)
	}
}

